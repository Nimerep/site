const assert = require('node:assert/strict');
const {recommend, requirements, economics} = require('../content/assets/eu-launch-planner.js');
const p = {model:'b2c',seller:'US',markets:['DE'],stock:'US',product:'standard',team:'none',system:'none',workflow:'standard',budget:'mid',priority:'simple',tracking:'ads',size:'micro',terms:'prepaid'};
assert.equal(recommend(p).choices[0].id,'shopify');
assert.equal(recommend({...p,system:'wordpress',team:'wordpress',priority:'control'}).choices[0].id,'woo');
assert.equal(recommend({...p,model:'b2b',system:'odoo',team:'partner',workflow:'company',budget:'high'}).choices[0].id,'odoo');
assert.equal(recommend({...p,model:'b2b',workflow:'company',budget:'low'}).status,'needs-budget');
assert(requirements(p).some(x=>x.id==='eu-b2c'));
assert(!requirements({...p,model:'b2b'}).some(x=>x.id==='eu-b2c'));
assert(requirements({...p,model:'b2b'}).some(x=>x.id==='privacy'));
assert(!requirements({...p,markets:['BE']}).some(x=>x.id==='BE-invoice'));
assert(requirements({...p,seller:'BE',markets:['BE'],model:'b2b'}).some(x=>x.id==='BE-invoice'));
assert(!requirements({...p,markets:['CH']}).some(x=>x.id==='eu-b2c'));
assert(requirements({...p,markets:['CH']}).some(x=>x.id==='CH'));
assert(requirements({...p,seller:'DE',markets:['CH']}).some(x=>x.id==='privacy'));
assert.equal(economics({price:100,basis:'net',days:'',finance:'',badDebt:''}),null);
assert(requirements({...p,markets:['otherEU']}).some(x=>x.id==='coverage'));
assert.equal(recommend({...p,budget:'unknown'}).status,'provisional');
assert.throws(()=>recommend({...p,markets:[]}));
const n={price:120,vat:20,basis:'gross',cogs:40,outbound:5,customerShipping:0,feePct:2,feeFixed:0.3,handling:2,returnRate:0,returnCost:8,writeoff:0,cac:10,fixed:1000,discount:0};
const result=economics(n);
assert.equal(economics({...n,days:'',finance:'',badDebt:''}),null);
assert(Math.abs(result.contribution-40.3)<1e-9);
assert.equal(result.breakEven,25);
assert(economics({...n,returnRate:20}).contribution<result.contribution);
assert(economics({...n,discount:50}).contribution<0);
assert.equal(economics({...n,price:''}),null);
assert.equal(economics({...n,price:0}).breakEven,null);
assert.throws(()=>economics({...n,returnRate:101}));
assert.throws(()=>economics({...n,feePct:-1}));
assert.throws(()=>economics({...n,price:Infinity}));
assert(economics({...n,days:60,finance:12,badDebt:2}).contribution<result.contribution);
console.log('EU planner: shortlist, jurisdiction, unknowns and money checks passed');
